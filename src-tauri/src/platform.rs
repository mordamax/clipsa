// OS integration: clipboard I/O, change detection, sensitive-content markers,
// frontmost application, accessibility permission, paste simulation, and
// (App Store edition) the SMAppService login item.

#[cfg(all(feature = "app-store", not(target_os = "macos")))]
compile_error!("the `app-store` feature is for the macOS App Store build only");

use std::sync::Mutex;

use serde::Serialize;

use crate::clipboard::Snapshot;
use crate::error::{ClipsaError, ClipsaResult};

/// Pasteboard types password managers attach to secrets
/// (http://nspasteboard.org).
#[cfg(target_os = "macos")]
const SENSITIVE_MARKERS: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
];

/// Clipboard formats Windows password managers register to opt out of
/// clipboard history / monitoring.
#[cfg(windows)]
const SENSITIVE_MARKERS: &[&str] = &[
    "ExcludeClipboardContentFromMonitorProcessing",
    "Clipboard Viewer Ignore",
];

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum PermissionState {
    Granted,
    Denied,
    NotRequired,
}

#[derive(Debug, Clone, Serialize)]
pub struct Permissions {
    pub accessibility: PermissionState,
}

pub struct Platform {
    clipboard: Mutex<Option<arboard::Clipboard>>,
}

impl Default for Platform {
    fn default() -> Self {
        Self::new()
    }
}

impl Platform {
    /// The OS clipboard is opened lazily on first use.
    pub fn new() -> Self {
        Self {
            clipboard: Mutex::new(None),
        }
    }

    fn with_clipboard<T>(
        &self,
        f: impl FnOnce(&mut arboard::Clipboard) -> ClipsaResult<T>,
    ) -> ClipsaResult<T> {
        let mut guard = self.clipboard.lock().unwrap_or_else(|p| p.into_inner());
        if guard.is_none() {
            *guard = Some(
                arboard::Clipboard::new()
                    .map_err(|e| ClipsaError::Clipboard(format!("Cannot open clipboard: {e}")))?,
            );
        }
        let result = f(guard.as_mut().expect("initialised above"));
        if result.is_err() {
            // Drop the handle so a broken connection (e.g. X11 restart) is
            // re-established on the next call.
            *guard = None;
        }
        result
    }

    /// Read the current clipboard value. Preference: files, rich text, plain
    /// text, image. `None` when empty, unsupported, or over the size limits.
    pub fn read(&self, capture_images: bool) -> ClipsaResult<Option<Snapshot>> {
        self.with_clipboard(|clipboard| {
            if let Some(paths) = optional(clipboard.get().file_list())? {
                let paths: Vec<String> = paths
                    .into_iter()
                    .map(|p| p.to_string_lossy().into_owned())
                    .collect();
                if !paths.is_empty() {
                    return Ok(Snapshot::Files(paths).validated());
                }
            }
            if let Some(text) = optional(clipboard.get().text())? {
                if !text.trim().is_empty() {
                    let snapshot = match optional(clipboard.get().html())? {
                        Some(html) if !html.trim().is_empty() => Snapshot::Html { html, text },
                        _ => Snapshot::Text(text),
                    };
                    return Ok(snapshot.validated());
                }
            }
            if capture_images {
                if let Some(image) = optional(clipboard.get().image())? {
                    return Ok(Snapshot::Image {
                        width: image.width as u32,
                        height: image.height as u32,
                        rgba: image.bytes.into_owned(),
                    }
                    .validated());
                }
            }
            Ok(None)
        })
    }

    pub fn write(&self, snapshot: &Snapshot) -> ClipsaResult<()> {
        self.with_clipboard(|clipboard| {
            let result = match snapshot {
                Snapshot::Text(text) => clipboard.set().text(text.as_str()),
                Snapshot::Html { html, text } => {
                    clipboard.set().html(html.as_str(), Some(text.as_str()))
                }
                Snapshot::Image {
                    width,
                    height,
                    rgba,
                } => clipboard.set().image(arboard::ImageData {
                    width: *width as usize,
                    height: *height as usize,
                    bytes: rgba.as_slice().into(),
                }),
                Snapshot::Files(paths) => clipboard.set().file_list(paths),
            };
            result.map_err(|e| ClipsaError::Clipboard(format!("Cannot write clipboard: {e}")))
        })
    }

    /// OS clipboard change counter, if the platform has one. When `None`,
    /// callers must read and compare content to detect changes.
    pub fn change_token(&self) -> Option<u64> {
        #[cfg(target_os = "macos")]
        return Some(macos::change_count());
        #[cfg(windows)]
        return Some(win::change_count());
        #[cfg(not(any(target_os = "macos", windows)))]
        None
    }

    /// Whether the current clipboard value is flagged as secret by its source
    /// (password managers). Not detectable on Linux.
    pub fn has_sensitive_marker(&self) -> bool {
        #[cfg(target_os = "macos")]
        return macos::has_any_type(SENSITIVE_MARKERS);
        #[cfg(windows)]
        return win::has_any_format(SENSITIVE_MARKERS);
        #[cfg(not(any(target_os = "macos", windows)))]
        false
    }

    /// Identifier of the frontmost application: macOS bundle id, Windows
    /// executable file name. Not available on Linux.
    pub fn frontmost_app(&self) -> Option<String> {
        #[cfg(target_os = "macos")]
        return macos::frontmost_bundle_id();
        #[cfg(windows)]
        return win::foreground_exe_name();
        #[cfg(not(any(target_os = "macos", windows)))]
        None
    }

    /// Accessibility is only needed to simulate ⌘V. The App Store edition
    /// never simulates input (not allowed in the sandbox), so it needs nothing.
    pub fn permissions(&self) -> Permissions {
        #[cfg(all(target_os = "macos", not(feature = "app-store")))]
        let accessibility = if macos::accessibility_trusted() {
            PermissionState::Granted
        } else {
            PermissionState::Denied
        };
        #[cfg(any(not(target_os = "macos"), feature = "app-store"))]
        let accessibility = PermissionState::NotRequired;
        Permissions { accessibility }
    }

    /// Ask the OS for the permissions paste simulation needs (macOS shows the
    /// Accessibility prompt; elsewhere, and in the App Store edition, nothing
    /// is required).
    pub fn request_permissions(&self) -> Permissions {
        #[cfg(all(target_os = "macos", not(feature = "app-store")))]
        if !macos::accessibility_trusted() {
            // Creating an Enigo instance with prompting enabled triggers the
            // system "allow accessibility" dialog.
            let _ = enigo::Enigo::new(&enigo::Settings {
                open_prompt_to_get_permissions: true,
                ..Default::default()
            });
        }
        self.permissions()
    }

    /// Whether the OS can verify the user (Touch ID / login password on macOS,
    /// Windows Hello on Windows). Not available on Linux.
    pub fn auth_supported(&self) -> bool {
        #[cfg(target_os = "macos")]
        return macos_auth::supported();
        #[cfg(windows)]
        return windows_hello::available();
        #[cfg(not(any(target_os = "macos", windows)))]
        false
    }

    /// Ask the OS to verify the user. Blocks until the prompt is answered.
    /// `reason` completes "Clipsa is trying to …" on macOS.
    pub fn authenticate(&self, reason: &str) -> ClipsaResult<()> {
        #[cfg(target_os = "macos")]
        let result = macos_auth::verify(reason);
        #[cfg(windows)]
        let result = windows_hello::verify(reason);
        #[cfg(not(any(target_os = "macos", windows)))]
        let result: Result<(), String> = {
            let _ = reason;
            Err("App lock is not available on this platform".into())
        };
        result.map_err(ClipsaError::Rejected)
    }

    /// Send the platform paste shortcut to the focused application. Not part
    /// of the App Store edition: the sandbox does not allow posting key events.
    #[cfg(not(feature = "app-store"))]
    pub fn simulate_paste(&self) -> ClipsaResult<()> {
        use enigo::{Direction, Key, Keyboard};

        if self.permissions().accessibility == PermissionState::Denied {
            return Err(ClipsaError::Platform(
                "Pasting needs accessibility permission".into(),
            ));
        }
        let mut enigo = enigo::Enigo::new(&enigo::Settings {
            open_prompt_to_get_permissions: false,
            ..Default::default()
        })
        .map_err(|e| ClipsaError::Platform(format!("Cannot simulate input: {e}")))?;
        #[cfg(target_os = "macos")]
        let modifier = Key::Meta;
        #[cfg(not(target_os = "macos"))]
        let modifier = Key::Control;
        let input_err = |e: enigo::InputError| ClipsaError::Platform(format!("Paste failed: {e}"));
        enigo.key(modifier, Direction::Press).map_err(input_err)?;
        let result = enigo.key(Key::Unicode('v'), Direction::Click);
        enigo.key(modifier, Direction::Release).map_err(input_err)?;
        result.map_err(input_err)
    }
}

/// Map "this format is not on the clipboard" to `None`.
fn optional<T>(result: Result<T, arboard::Error>) -> ClipsaResult<Option<T>> {
    match result {
        Ok(value) => Ok(Some(value)),
        Err(arboard::Error::ContentNotAvailable) | Err(arboard::Error::ConversionFailure) => {
            Ok(None)
        }
        Err(arboard::Error::ClipboardNotSupported) => Ok(None),
        Err(e) => Err(ClipsaError::Clipboard(e.to_string())),
    }
}

#[cfg(target_os = "macos")]
mod macos {
    use objc2_app_kit::{NSPasteboard, NSWorkspace};

    #[cfg(not(feature = "app-store"))]
    #[link(name = "ApplicationServices", kind = "framework")]
    extern "C" {
        fn AXIsProcessTrusted() -> bool;
    }

    pub fn change_count() -> u64 {
        NSPasteboard::generalPasteboard().changeCount() as u64
    }

    pub fn has_any_type(markers: &[&str]) -> bool {
        let Some(types) = NSPasteboard::generalPasteboard().types() else {
            return false;
        };
        types
            .iter()
            .any(|t| markers.iter().any(|marker| t.to_string() == *marker))
    }

    pub fn frontmost_bundle_id() -> Option<String> {
        NSWorkspace::sharedWorkspace()
            .frontmostApplication()?
            .bundleIdentifier()
            .map(|id| id.to_string())
    }

    #[cfg(not(feature = "app-store"))]
    pub fn accessibility_trusted() -> bool {
        // SAFETY: no arguments; reads process trust state.
        unsafe { AXIsProcessTrusted() }
    }
}

#[cfg(target_os = "macos")]
mod macos_auth {
    use std::sync::{mpsc, Mutex};

    use block2::RcBlock;
    use objc2::runtime::Bool;
    use objc2_foundation::{NSError, NSString};
    use objc2_local_authentication::{LAContext, LAPolicy};

    // Touch ID / Apple Watch with the login password as fallback.
    const POLICY: LAPolicy = LAPolicy::DeviceOwnerAuthentication;

    pub fn supported() -> bool {
        // SAFETY: fresh context, synchronous preflight check.
        unsafe { LAContext::new().canEvaluatePolicy_error(POLICY) }.is_ok()
    }

    pub fn verify(reason: &str) -> Result<(), String> {
        // SAFETY: plain allocation.
        let context = unsafe { LAContext::new() };
        let (sender, receiver) = mpsc::channel();
        let sender = Mutex::new(Some(sender));
        let reply = RcBlock::new(move |success: Bool, error: *mut NSError| {
            let result = if success.as_bool() {
                Ok(())
            } else {
                // SAFETY: the framework passes either null or a valid NSError.
                Err(unsafe { error.as_ref() }
                    .map(|e| e.localizedDescription().to_string())
                    .unwrap_or_else(|| "Authentication failed".into()))
            };
            if let Some(sender) = sender.lock().unwrap_or_else(|p| p.into_inner()).take() {
                let _ = sender.send(result);
            }
        });
        // SAFETY: the reply block only sends on a channel (Send); `context`
        // stays alive until the reply arrives because we block on `receiver`.
        unsafe {
            context.evaluatePolicy_localizedReason_reply(
                POLICY,
                &NSString::from_str(reason),
                &reply,
            );
        }
        receiver
            .recv()
            .unwrap_or_else(|_| Err("Authentication was interrupted".into()))
    }
}

/// Launch at login for the App Store edition, via
/// `SMAppService.mainAppService` (macOS 13+). The sandbox blocks the
/// LaunchAgent that [`autostart`] writes.
#[cfg(feature = "app-store")]
pub mod login_item {
    use objc2_service_management::{SMAppService, SMAppServiceStatus};

    use crate::error::{ClipsaError, ClipsaResult};

    /// Whether macOS will open Clipsa at login (registered and approved).
    pub fn is_enabled() -> bool {
        // SAFETY: class method without arguments; `status` is a plain getter.
        unsafe { SMAppService::mainAppService().status() == SMAppServiceStatus::Enabled }
    }

    /// Register or unregister the main app as a login item.
    pub fn set(enabled: bool) -> ClipsaResult<()> {
        // SAFETY: class method without arguments.
        let service = unsafe { SMAppService::mainAppService() };
        // SAFETY: plain getter.
        let status = unsafe { service.status() };
        if enabled {
            if status != SMAppServiceStatus::Enabled {
                // SAFETY: no arguments besides the out-error handled by objc2.
                unsafe { service.registerAndReturnError() }.map_err(|e| {
                    ClipsaError::Platform(format!(
                        "Could not add Clipsa to the login items: {}",
                        e.localizedDescription()
                    ))
                })?;
            }
            // SAFETY: plain getter.
            if unsafe { service.status() } == SMAppServiceStatus::RequiresApproval {
                return Err(ClipsaError::Platform(
                    "Allow Clipsa in System Settings → General → Login Items to open it at login"
                        .into(),
                ));
            }
        } else if status == SMAppServiceStatus::Enabled
            || status == SMAppServiceStatus::RequiresApproval
        {
            // SAFETY: as above.
            unsafe { service.unregisterAndReturnError() }.map_err(|e| {
                ClipsaError::Platform(format!(
                    "Could not remove Clipsa from the login items: {}",
                    e.localizedDescription()
                ))
            })?;
        }
        Ok(())
    }
}

/// Launch at login for direct-download builds (`auto-launch`): a LaunchAgent
/// on macOS, a `Run` registry value on Windows, an XDG autostart entry on
/// Linux. The entry passes `--launched-at-login` so a login start can stay in
/// the tray, which an SMAppService login item can't do.
#[cfg(not(feature = "app-store"))]
pub mod autostart {
    use std::path::Path;

    use auto_launch::{AutoLaunch, AutoLaunchBuilder};

    use crate::error::{ClipsaError, ClipsaResult};

    fn platform_err(e: impl std::fmt::Display) -> ClipsaError {
        ClipsaError::Platform(e.to_string())
    }

    pub struct Autostart {
        entry: AutoLaunch,
        bundle_id: String,
        name: String,
    }

    impl Autostart {
        /// `name` names the entry (`~/Library/LaunchAgents/<name>.plist`, the
        /// registry value, the `.desktop` file) and must stay stable so
        /// existing entries are found. `appimage` is the AppImage path when
        /// running from one, which is what has to be launched.
        pub fn new(
            name: &str,
            bundle_id: &str,
            arg: &str,
            appimage: Option<&Path>,
        ) -> ClipsaResult<Self> {
            let exe = std::env::current_exe().map_err(platform_err)?;
            let path = match appimage {
                Some(appimage) => appimage.to_path_buf(),
                // macOS: the binary inside the .app, with symlinks resolved.
                None if cfg!(target_os = "macos") => exe.canonicalize().map_err(platform_err)?,
                None => exe,
            };
            let entry = AutoLaunchBuilder::new()
                .set_app_name(name)
                .set_app_path(&path.to_string_lossy())
                .set_args(&[arg])
                .set_macos_launch_mode(auto_launch::MacOSLaunchMode::LaunchAgent)
                // Without AssociatedBundleIdentifiers, macOS 13+ attributes the
                // LaunchAgent to the developer named in the code signature
                // ("<developer> added items that can run in the background")
                // instead of showing Clipsa's name and icon. Ignored elsewhere.
                .set_bundle_identifiers(&[bundle_id])
                .build()
                .map_err(platform_err)?;
            Ok(Self {
                entry,
                bundle_id: bundle_id.to_owned(),
                name: name.to_owned(),
            })
        }

        /// Create or remove the entry. An enabled macOS entry written by an
        /// older version (no bundle identifier) is rewritten.
        pub fn set(&self, enabled: bool) -> ClipsaResult<()> {
            let current = self.entry.is_enabled().map_err(platform_err)?;
            if enabled && (!current || self.needs_rewrite()) {
                self.entry.enable().map_err(platform_err)
            } else if !enabled && current {
                self.entry.disable().map_err(platform_err)
            } else {
                Ok(())
            }
        }

        /// macOS LaunchAgents written before 0.1.2 have no bundle identifier.
        fn needs_rewrite(&self) -> bool {
            if !cfg!(target_os = "macos") {
                return false;
            }
            let Some(home) = dirs::home_dir() else {
                return false;
            };
            let plist = home.join(format!("Library/LaunchAgents/{}.plist", self.name));
            std::fs::read_to_string(plist)
                .is_ok_and(|text| !text.contains(&format!("<string>{}</string>", self.bundle_id)))
        }
    }
}

#[cfg(windows)]
mod windows_hello {
    use windows::core::{factory, HSTRING};
    use windows::Security::Credentials::UI::{
        UserConsentVerificationResult, UserConsentVerifier, UserConsentVerifierAvailability,
    };
    use windows::Win32::System::WinRT::IUserConsentVerifierInterop;
    use windows::Win32::UI::WindowsAndMessaging::GetForegroundWindow;
    use windows_future::IAsyncOperation;

    pub fn available() -> bool {
        UserConsentVerifier::CheckAvailabilityAsync()
            .and_then(|op| op.join())
            .is_ok_and(|a| a == UserConsentVerifierAvailability::Available)
    }

    pub fn verify(reason: &str) -> Result<(), String> {
        let interop = factory::<UserConsentVerifier, IUserConsentVerifierInterop>()
            .map_err(|e| e.message())?;
        // SAFETY: plain call; the user just clicked Unlock, so a Clipsa window is in front.
        let hwnd = unsafe { GetForegroundWindow() };
        // SAFETY: `hwnd` is a window handle; a null handle makes the call fail with an error.
        let op: IAsyncOperation<UserConsentVerificationResult> =
            unsafe { interop.RequestVerificationForWindowAsync(hwnd, &HSTRING::from(reason)) }
                .map_err(|e| e.message())?;
        match op.join().map_err(|e| e.message())? {
            UserConsentVerificationResult::Verified => Ok(()),
            UserConsentVerificationResult::Canceled => Err("Authentication cancelled".into()),
            other => Err(format!("Windows Hello verification failed ({})", other.0)),
        }
    }
}

#[cfg(windows)]
mod win {
    use windows_sys::Win32::Foundation::CloseHandle;
    use windows_sys::Win32::System::DataExchange::{
        GetClipboardSequenceNumber, IsClipboardFormatAvailable, RegisterClipboardFormatW,
    };
    use windows_sys::Win32::System::Threading::{
        OpenProcess, QueryFullProcessImageNameW, PROCESS_NAME_WIN32,
        PROCESS_QUERY_LIMITED_INFORMATION,
    };
    use windows_sys::Win32::UI::WindowsAndMessaging::{
        GetForegroundWindow, GetWindowThreadProcessId,
    };

    pub fn change_count() -> u64 {
        // SAFETY: no arguments.
        u64::from(unsafe { GetClipboardSequenceNumber() })
    }

    pub fn has_any_format(names: &[&str]) -> bool {
        names.iter().any(|name| {
            let wide: Vec<u16> = name.encode_utf16().chain(std::iter::once(0)).collect();
            // SAFETY: `wide` is a NUL-terminated UTF-16 string that outlives the call.
            let format = unsafe { RegisterClipboardFormatW(wide.as_ptr()) };
            // SAFETY: plain value argument.
            format != 0 && unsafe { IsClipboardFormatAvailable(format) } != 0
        })
    }

    pub fn foreground_exe_name() -> Option<String> {
        // SAFETY: every handle is checked before use and closed afterwards;
        // the buffer length passed matches the buffer.
        unsafe {
            let hwnd = GetForegroundWindow();
            if hwnd.is_null() {
                return None;
            }
            let mut pid = 0u32;
            GetWindowThreadProcessId(hwnd, &mut pid);
            if pid == 0 {
                return None;
            }
            let process = OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, 0, pid);
            if process.is_null() {
                return None;
            }
            let mut buffer = [0u16; 1024];
            let mut len = buffer.len() as u32;
            let ok = QueryFullProcessImageNameW(
                process,
                PROCESS_NAME_WIN32,
                buffer.as_mut_ptr(),
                &mut len,
            );
            CloseHandle(process);
            if ok == 0 {
                return None;
            }
            let path = String::from_utf16_lossy(&buffer[..len as usize]);
            path.rsplit('\\').next().map(str::to_string)
        }
    }
}
